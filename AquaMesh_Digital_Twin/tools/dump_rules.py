#!/usr/bin/env python3
"""Print the rule base as Markdown (used to generate docs/RULES.md)."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from engine.knowledge import KB
print(f"# AquaMesh rule base `{KB.version}`  ({len(KB.rules)} rules, {len(KB.facts)} facts)\n")
print("Generated by `python3 tools/dump_rules.py`. Premises prefixed with ¬ must be FALSE. Several rules with the same head are alternatives (OR).\n")
print("## Evidence facts (layer 0, produced from sensors / links)\n\n| fact | label | domain | meaning |\n|---|---|---|---|")
for n, m in KB.facts.items():
    if m["kind"] == "evidence": print(f"| `{n}` | {m['label']} | {m['domain']} | {m['desc']} |")
print("\n## Rules\n\n| id | conclusion (layer) | IF | meaning |\n|---|---|---|---|")
for r in KB.rules:
    body = " AND ".join(("¬" if not w else "") + f"`{f}`" for f, w in r.body)
    print(f"| {r.id} | `{r.head}` (L{KB.layer[r.head]}) | {body} | {r.text} |")
